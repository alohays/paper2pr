#!/usr/bin/env python3
"""Package rendered audience pages and the assets they reference."""

from __future__ import annotations

import argparse
import fcntl
import os
import shutil
import sys
import tempfile
from pathlib import Path

import build_landing
import check_site_assets as assets
import deckpath
import deckprofile
from strip_speaker_notes import strip_notes

ROOT = Path(__file__).resolve().parent.parent
SITE_MARKER = "Generated by Paper2PR.\n"
REDIRECTS = {"papers/DreamDojo", "papers/DreamZero", "papers/RoboTTT", "talks/SUNY"}


def select_decks(refs, preview):
    all_decks = deckpath.all_decks()
    available = all_decks if preview else deckprofile.publishable_decks()
    if not refs:
        return available, []
    selected = []
    fixtures = []
    for ref in refs:
        source = Path(ref).resolve()
        if preview and source.is_relative_to(ROOT / "Quarto" / "_fixtures"):
            if not source.is_file() or source.suffix != ".qmd":
                raise ValueError("a fixture preview requires its .qmd source")
            fixtures.append(source)
            continue
        deck = deckpath.find(ref)
        if deck not in available:
            raise ValueError("requested deck is excluded from this publication")
        selected.append(deck)
    return selected, fixtures


def allowed_asset(path, selected, owners, all_decks, preview):
    """Keep selected pages and referenced assets within their publishing scope."""
    parts = path.parts
    if parts[:2] == ("slides", "fonts"):
        return True
    if len(parts) < 3:
        return False
    root, genre, owner = parts[:3]
    if genre == "_fixtures":
        return bool(preview and root == "slides")
    if genre not in deckpath.genres():
        return False
    if root == "Figures":
        return owner == "_series" or (genre, owner) in owners
    if root != "slides":
        return False
    # Bundles and loose assets conventionally owned by another deck must
    # not leak across the boundary even when referenced by a public page.
    for deck in sorted(all_decks, key=lambda d: -len(d.name)):
        if deck.genre != genre:
            continue
        if owner == deck.name + ".html":
            return (genre, deck.name) in selected
        if (owner == deck.name or owner == f"{deck.name}_files" or
                owner.startswith((deck.name + ".", deck.name + "-"))):
            return (genre, deck.name) in owners
    return not owner.startswith("_")


def assemble(site, selected, fixtures, preview):
    site.mkdir()
    (site / "slides").mkdir()
    (site / ".nojekyll").write_text(SITE_MARKER, encoding="utf-8")
    (site / "index.html").write_text(build_landing.build(selected), encoding="utf-8")
    all_decks = deckpath.all_decks()
    selected_ids = {(deck.genre, deck.name) for deck in selected}
    owners = selected_ids | {(deck.genre, deck.name) for deck in deckprofile.publishable_decks()}
    # The design fixture exercises real deck figures even when their owners
    # opt out of Pages. Fixture previews are confined to ignored exports/.
    if fixtures:
        owners.update((deck.genre, deck.name) for deck in all_decks)
    sources = [deck.qmd for deck in selected] + fixtures
    queue = [Path("slides") / qmd.relative_to(ROOT / "Quarto").with_suffix(".html")
             for qmd in sources]
    # Code that constructs a URL at runtime can name that file in the deck
    # config. HTML, CSS and SVG dependencies of such a file are still followed.
    for deck in selected:
        extras = deckprofile.load(deck).raw.get("runtime_assets", [])
        if not isinstance(extras, list) or not all(isinstance(url, str) for url in extras):
            raise ValueError("runtime_assets must be a list of paths relative to the deck")
        page = f"slides/{deck.slug}.html"
        queue.extend(assets.site_target(page, url) for url in extras)
    seen = set()
    while queue:
        path = queue.pop()
        if path in seen:
            continue
        seen.add(path)
        if not assets.runtime_path(path, preview == "classroom") or not allowed_asset(
                path, selected_ids, owners, all_decks, preview):
            raise ValueError("a rendered page references a private, excluded or authoring asset")
        src = ROOT / ("Quarto" if path.parts[0] == "slides" else "Figures")
        src = src.joinpath(*path.parts[1:])
        if not src.is_file() or src.resolve() != src:
            raise ValueError("a referenced runtime file is missing or links outside its asset directory")
        dest = site / path
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dest)
        if path.suffix.lower() in assets.FONT_SUFFIXES:
            queue.extend(path.with_name(notice) for notice in assets.FONT_NOTICES
                         if (src.parent / notice).is_file())
        if path.suffix.lower() == ".html":
            # Follow references only AFTER removing notes from this copy.
            strip_notes(dest)
        if path.suffix.lower() in assets.SCAN_REFS:
            queue.extend(assets.site_target(path, url) for url in assets.refs_in(dest))
    for deck in selected:
        if deck.slug in REDIRECTS:
            target = deck.slug + ".html"
            (site / "slides" / f"{deck.name}.html").write_text(
                '<!doctype html>\n<html lang="en"><head><meta charset="utf-8">\n'
                f'<title>Moved</title><link rel="canonical" href="{target}">\n'
                f'<meta http-equiv="refresh" content="0; url={target}"></head>\n'
                f'<body><a href="{target}">View slides</a></body></html>\n', encoding="utf-8")
    return assets.validate(site, classroom=preview == "classroom")


def replace_output(work, dest):
    """Swap a verified build into a generated output directory, preserving unrelated data."""
    parent = os.open(dest.parent, os.O_RDONLY)
    try:
        fcntl.flock(parent, fcntl.LOCK_EX)
        if dest.is_symlink() or (dest.exists() and not dest.is_dir()):
            raise ValueError("output must be a generated site directory")
        previous = work / "previous"
        if dest.exists() and any(dest.iterdir()):
            marker = dest / ".nojekyll"
            owned = marker.is_file() and marker.read_text(encoding="utf-8") == SITE_MARKER
            if not owned:
                legacy = (dest in (ROOT / "_site", ROOT / "docs") and marker.is_file()
                          and (dest / "index.html").is_file() and (dest / "slides").is_dir())
                if not legacy:
                    raise ValueError("refusing to replace a nonempty directory without a Paper2PR site marker")
                # An old preview may contain unrelated author files. Keep the
                # entire original on its first upgrade, outside the public site.
                backups = ROOT / "exports"
                backups.mkdir(exist_ok=True)
                previous = Path(tempfile.mkdtemp(dir=backups, prefix="legacy-site-")) / dest.name
        if dest.exists():
            dest.rename(previous)
        try:
            (work / "site").rename(dest)
        except OSError:
            if previous.exists():
                previous.rename(dest)
            raise
        if previous.parent != work:
            print(f"Previous preview preserved in {previous.relative_to(ROOT)}")
    finally:
        os.close(parent)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview", choices=["public", "classroom"],
                        help="verify one deck or fixture locally inside exports/")
    parser.add_argument("output", type=Path, nargs="?", default=Path("_site"))
    parser.add_argument("decks", nargs="*", help="deck name or genre/name")
    args = parser.parse_args()
    dest = args.output.absolute()
    if dest.is_symlink():
        parser.exit(2, "output must not be a symlink\n")
    dest = dest.resolve()
    if args.preview and (len(args.decks) != 1 or dest == ROOT / "exports"
                         or not dest.is_relative_to(ROOT / "exports")):
        parser.exit(2, "a private preview requires one deck and an output inside exports/\n")
    if ROOT.is_relative_to(dest):
        parser.exit(2, "output cannot contain the source checkout\n")
    try:
        selected, fixtures = select_decks(args.decks, args.preview)
        dest.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix=".build-site-", dir=dest.parent) as td:
            work = Path(td)
            count = assemble(work / "site", selected, fixtures, args.preview)
            replace_output(work, dest)
    except (OSError, ValueError, deckpath.DeckNotFound, deckpath.AmbiguousDeck,
            deckprofile.ConfigError) as exc:
        parser.exit(1, "assembly failed: " + assets.safe_error(exc) + "\n")
    print(f"Assembled {len(selected) + len(fixtures)} deck(s). All {count} local references resolve.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
